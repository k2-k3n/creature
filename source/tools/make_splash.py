#!/usr/bin/env python3
"""MIT. Bake Creature's eye blink from the app rig into the Box boot splash."""
from array import array
from itertools import groupby
import os
from pathlib import Path
import struct
import subprocess
from tempfile import TemporaryDirectory
import zlib

ROOT = Path(__file__).resolve().parent.parent
W, H = 320, 172
GROUND = 0x2044  # RGB565 for the app's (37, 10, 33)


def render():
    sdk = os.environ["RESONA_SDK"]
    with TemporaryDirectory() as tmp:
        exe, raw = Path(tmp) / "frames", Path(tmp) / "frames.raw"
        subprocess.run(["clang++", "-std=c++17", "-O2", "-DRESONA_LAB_HOST",
                        f"-I{sdk}", f"-I{ROOT / 'src'}", "-include", "cmath",
                        str(ROOT / "tools/splash_frames.cpp"), "-o", str(exe)], check=True)
        subprocess.run([str(exe), str(raw)], check=True)
        return array("H", raw.read_bytes())[:W * H]


def blend(color, alpha):
    channels = [(int((GROUND >> shift & mask) * (1 - alpha)
                     + (color >> shift & mask) * alpha + 0.5) << shift)
                for shift, mask in ((11, 31), (5, 63), (0, 31))]
    return sum(channels)


def main():
    art = render()
    eyes = []
    for x0, y0, x1, y1, center in ((84, 36, 140, 86, 63), (176, 42, 232, 82, 62)):
        # The cream whites are the bright, low-blue pixels in the original eyes.
        points = [(x, y) for y in range(y0, y1) for x in range(x0, x1)
                  if (color := art[y * W + x]) >> 11 >= 20
                  and (color >> 5 & 63) >= 35 and (color & 31) < 24]
        assert points
        eyes.append((center, points))

    poses = [(0, 1), (.24, 1), (.55, 1), (.72, 1), (.72, 1), (.72, .62),
             (.72, .10), (.72, .46), (.72, .86), (.72, 1), (.6, 1), (.38, 1),
             (.16, 1), (0, 1)]
    hold = 48
    payload = bytearray()
    for alpha, opening in poses:
        frame = [GROUND] * (W * H)
        for center, points in eyes:
            for x, y in points:
                frame[round(center + (y - center) * opening) * W + x] = blend(0xddd1, alpha)
        runs = [(sum(1 for _ in run), color) for color, run in groupby(frame)]
        payload += struct.pack("<II", hold, len(runs))
        for length, color in runs:
            payload += struct.pack("<HH", length, color)
    data = struct.pack("<4s7I", b"RSP1", len(payload) + 32, zlib.crc32(payload),
                       hold * len(poses), W, H, len(poses), 0) + payload
    assert len(data) <= 24576
    rows = [", ".join(map(str, data[i:i+24])) for i in range(0, len(data), 24)]
    (ROOT / "src/splash_data.h").write_text(
        "// Generated by tools/make_splash.py. MIT.\n#pragma once\n#include <stdint.h>\n"
        "alignas(4) static const uint8_t kSplash[] = {\n " + ",\n ".join(rows) + "\n};\n")
    print(f"{len(poses)} frames, {len(data)} bytes, {hold * len(poses)} ms")


if __name__ == "__main__":
    main()
